def generate_demo_assistant_reply(context_dict: Dict[str, Any]) -> AssistantResponse:
    """Builds a deterministic, transparent response based on server-computed event metrics."""
    event_data = context_dict["event"]
    b_sum = context_dict["budget_summary"]
    t_sum = context_dict["task_summary"]
    currency = event_data["currency"]

    reply_lines = [
        "Demo mode: this answer was not generated by an AI model.",
        "",
        f"Event: {event_data['name']} ({event_data['event_type']}) scheduled for {event_data['event_date']} in {event_data['location']}.",
        f"Budget Summary: Total allocated {currency} {b_sum['total_budget']}, Actual spend {currency} {b_sum['total_actual']}, Remaining {currency} {b_sum['remaining']}.",
        f"Tasks Status: {t_sum['completed']} of {t_sum['total']} completed ({t_sum['progress_percent']}%). Overdue: {t_sum['overdue']}, Upcoming: {t_sum['upcoming']}.",
    ]

    pending = b_sum.get("pending_payments") or []
    if pending:
        reply_lines.append(f"Pending Payments: {len(pending)} item(s) totaling {currency} {b_sum['pending_total']}.")

    reply_lines.extend([
        "",
        "Questions that require a configured Gemini API key (GEMINI_API_KEY):",
        "• Creative theme, color palette, and decor conceptualization",
        "• Deep cost-reduction strategies and vendor contract negotiation advice",
        "• Personalized invitation wording and multi-lingual copywriting",
        "• Complex schedule and contingency risk evaluations",
    ])

    recommendations: List[AssistantRecommendationItem] = []
    if t_sum["overdue"] > 0:
        recommendations.append(
            AssistantRecommendationItem(
                title="Review Overdue Tasks",
                detail=f"You currently have {t_sum['overdue']} task(s) past their due date. Visit the Timeline & Tasks tab to reschedule or update.",
            )
        )
    if b_sum.get("over_budget"):
        recommendations.append(
            AssistantRecommendationItem(
                title="Address Budget Overrun",
                detail="Actual expenditures have exceeded your total event budget. Consider reallocating from remaining category allowances.",
            )
        )
    else:
        recommendations.append(
            AssistantRecommendationItem(
                title="Maintain Expense Records",
                detail=f"You have {currency} {b_sum['remaining']} remaining in your overall budget. Keep recording actual quotes and invoices.",
            )
        )

    suggested_prompts = [
        "Which budget categories have the highest allocation?",
        "What are my highest priority upcoming tasks?",
        "How can I save ₹20,000 on catering and decor?",
    ]

    return AssistantResponse(
        reply="\n".join(reply_lines),
        recommendations=recommendations[:5],
        suggested_modification_prompts=suggested_prompts[:3],
        changes_applied=False,
        source="demo",
        model=None,
        generated_at=get_now(),
    )


def build_assistant_user_prompt(
    rendered_context: str,
    history: Optional[List[ChatHistoryItem]],
    message: str,
) -> str:
    """Combines rendered context, last 10 history items, and message with prompt-injection defense."""
    # Truncate history to at most 10 items
    history_items = (history or [])[-10:]
    history_lines = []
    for item in history_items:
        history_lines.append(f"{item.role}: {item.content[:2000]}")
    history_str = "\n".join(history_lines) if history_lines else "No previous conversation"

    return (
        f"{rendered_context}\n\n"
        f"{format_untrusted_block('chat_history', history_str)}\n\n"
        f"{format_untrusted_block('user_message', message[:2000])}\n\n"
        f"Instructions for Response:\n"
        f"1. Address the user's message using the verified event context.\n"
        f"2. Provide between 0 and 5 concrete recommendations in `recommendations`.\n"
        f"3. Provide between 0 and 3 short example prompts in `suggested_modification_prompts` that the user could use in Modify mode (e.g. 'Move 20000 from decoration to catering').\n"
        f"4. Never claim any change has been executed (changes_applied is always false)."
    )


async def process_assistant_query(
    event_id: str,
    payload: AssistantRequest,
    ai_service: AIService,
    db: Optional[Session] = None,
) -> AssistantResponse:
    """Processes Ask mode query against the specified event."""
    start_time = time.perf_counter()

    # Step 1: Read event context in a short read session (no open transaction during AI call)
    context_result = build_event_context(event_id, db=db)
    if db is not None:
        db.rollback()  # Release read transaction/lock before calling Gemini

    if not context_result:
        logger.warning(
            "assistant_query event_not_found path=/api/events/%s/assistant event_id=%s outcome=404",
            event_id,
            event_id,
        )
        raise HTTPException(status_code=404, detail="Event not found")

    context_dict, rendered_context = context_result

    # Step 2: Handle Demo mode if Gemini is not configured
    if not ai_service.is_configured:
        duration = time.perf_counter() - start_time
        logger.info(
            "assistant_query demo_mode path=/api/events/%s/assistant event_id=%s duration=%.3fs outcome=200",
            event_id,
            event_id,
            duration,
        )
        return generate_demo_assistant_reply(context_dict)

    # Step 3: Format prompt and call Gemini AI
    user_prompt = build_assistant_user_prompt(rendered_context, payload.history, payload.message)

    try:
        raw_output, source, model = await ai_service.generate_structured(
            system_prompt=ASSISTANT_SYSTEM_PROMPT,
            user_prompt=user_prompt,
            response_model=AIAssistantResponse,
        )
    except Exception as exc:
        duration = time.perf_counter() - start_time
        logger.error(
            "assistant_query error path=/api/events/%s/assistant event_id=%s duration=%.3fs outcome=%s exception=%s",
            event_id,
            event_id,
            duration,
            getattr(exc, "status_code", 500),
            exc.__class__.__name__,
        )
        raise

    duration = time.perf_counter() - start_time
    logger.info(
        "assistant_query success path=/api/events/%s/assistant event_id=%s duration=%.3fs outcome=200",
        event_id,
        event_id,
        duration,
    )

    return AssistantResponse(
        reply=raw_output.reply,
        recommendations=raw_output.recommendations[:5],
        suggested_modification_prompts=raw_output.suggested_modification_prompts[:3],
        changes_applied=False,
        source=source,
        model=model,
        generated_at=get_now(),
    )
