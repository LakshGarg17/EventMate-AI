def test_assistant_mocked_gemini_call_and_prompt_contents(client, populated_event, freeze_today):
    freeze_today(date(2026, 10, 30))
    mock_json = """
    {
        "reply": "Based on your 800,000 INR budget and 4 allocated categories, you can save 20,000 by standardizing decor florals.",
        "recommendations": [
            {"title": "Renegotiate decor florals", "detail": "Opt for seasonal marigolds."}
        ],
        "suggested_modification_prompts": [
            "Move 20000 from Decoration to Catering"
        ]
    }
    """
    mock_resp = MagicMock()
    mock_resp.text = mock_json

    captured_prompt = {}

    def capture_gen(*args, **kwargs):
        captured_prompt["contents"] = kwargs.get("contents")
        return mock_resp

    with patch("app.config.settings.gemini_api_key", "test_gemini_secret_api_key_12345"):
        with patch.object(AIService, "is_configured", True):
            with patch("app.services.ai_service.genai.Client") as mock_client_cls:
                mock_client_instance = MagicMock()
                mock_client_instance.models.generate_content.side_effect = capture_gen
                mock_client_cls.return_value = mock_client_instance

                # 15 history items to test truncation to 10
                history = [{"role": "user" if i % 2 == 0 else "assistant", "content": f"Msg {i}"} for i in range(15)]

                res = client.post(
                    f"/api/events/{populated_event}/assistant",
                    json={
                        "message": "How can I optimize our wedding decor?",
                        "history": history,
                    },
                )
                assert res.status_code == 200
                data = res.json()
                assert data["source"] == "gemini"
                assert data["changes_applied"] is False
                assert len(data["recommendations"]) == 1
                assert data["recommendations"][0]["title"] == "Renegotiate decor florals"
                assert data["suggested_modification_prompts"] == ["Move 20000 from Decoration to Catering"]

                # Check prompt contents
                prompt_text = captured_prompt.get("contents", "")
                assert "Ananya & Kabir Wedding" in prompt_text
                assert "Book Folk Dancers Troupe" in prompt_text
                assert "Venue" in prompt_text and "Catering" in prompt_text
                assert "800000.00" in prompt_text

                # Redaction checks: secrets and contact info MUST NOT appear
                assert "SECRET_PHONE_9876543210" not in prompt_text
                assert "secret_email@folk.com" not in prompt_text
                assert "test_gemini_secret_api_key_12345" not in prompt_text

                # History check: only last 10 messages present, Msg 0 to 4 dropped
                assert "Msg 14" in prompt_text
                assert "Msg 5" in prompt_text
                assert "Msg 0" not in prompt_text


def test_assistant_gemini_error_mappings(client, populated_event):
    with patch("app.config.settings.gemini_api_key", "test_key"):
        with patch.object(AIService, "is_configured", True):
            with patch("app.services.ai_service.genai.Client") as mock_client_cls:
                mock_client_instance = MagicMock()
                mock_client_cls.return_value = mock_client_instance

                # 1. Timeout -> 504
                import asyncio
                mock_client_instance.models.generate_content.side_effect = asyncio.TimeoutError()
                res = client.post(f"/api/events/{populated_event}/assistant", json={"message": "Timeout test"})
                assert res.status_code == 504

                # 2. Rate Limit (429) -> 429
                mock_client_instance.models.generate_content.side_effect = errors.APIError(429, "Quota exhausted")
                res = client.post(f"/api/events/{populated_event}/assistant", json={"message": "Quota test"})
                assert res.status_code == 429

                # 3. Auth error (401) -> 502
                mock_client_instance.models.generate_content.side_effect = errors.APIError(401, "API_KEY_INVALID")
                res = client.post(f"/api/events/{populated_event}/assistant", json={"message": "Auth test"})
                assert res.status_code == 502

                # 4. Empty output -> 502
                mock_empty = MagicMock(text="")
                mock_client_instance.models.generate_content.side_effect = None
                mock_client_instance.models.generate_content.return_value = mock_empty
                res = client.post(f"/api/events/{populated_event}/assistant", json={"message": "Empty test"})
                assert res.status_code == 502

