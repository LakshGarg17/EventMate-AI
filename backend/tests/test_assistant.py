def test_assistant_validation_errors(client, populated_event):
    # Empty message
    res = client.post(f"/api/events/{populated_event}/assistant", json={"message": "   "})
    assert res.status_code == 422

    # Missing message
    res = client.post(f"/api/events/{populated_event}/assistant", json={})
    assert res.status_code == 422

    # Message exceeds 2000 chars
    res = client.post(f"/api/events/{populated_event}/assistant", json={"message": "x" * 2001})
    assert res.status_code == 422

    # Extra fields forbidden
    res = client.post(
        f"/api/events/{populated_event}/assistant",
        json={"message": "valid", "extra_field": "hack"},
    )
    assert res.status_code == 422


